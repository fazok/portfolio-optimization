"""Markdown report."""

from __future__ import annotations

from pathlib import Path

import pandas as pd


def _md(df: pd.DataFrame, floatfmt: str = ".2f", index: bool = True) -> str:
    df = df.reset_index() if index else df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: "" if pd.isna(v) else format(v, floatfmt))
    header = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def write_report(path: Path, ctx: dict) -> Path:
    tan, ew = ctx["split"]["tangency"], ctx["split"]["equal_weight"]

    def sr(x):
        return x[0] / x[1]

    lines = [
        "# Portfolio optimisation: walk-forward report",
        "",
        f"*Data: **{ctx['source']}**, {ctx['assets']}. Out-of-sample period {ctx['start']} to "
        f"{ctx['end']}. Monthly rebalancing on a rolling {ctx['lookback']}-day window, "
        f"long-only, max {100 * ctx['cap']:.0f}% per asset, {ctx['cost_bps']:.0f} bp costs.*",
        "",
        "Generated by `scripts/run_backtest.py`. Do not edit by hand.",
        "",
        "## 1. The Markowitz frontier (full sample, in-sample)",
        "",
        "![Frontier](figures/frontier.png)",
        "",
        "## 2. Estimation error",
        "",
        f"Frontier estimated on data up to {ctx['split']['split']}, then held. The tangency "
        f"portfolio promised a Sharpe ratio of {sr(tan['promised']):.2f} and delivered "
        f"{sr(tan['realised']):.2f}; 1/N promised {sr(ew['promised']):.2f} and delivered "
        f"{sr(ew['realised']):.2f}.",
        "",
        "![Split frontier](figures/frontier_oos.png)",
        "",
        "## 3. Walk-forward performance (net of costs)",
        "",
        _md(ctx["performance"]),
        "",
        "![Wealth](figures/wealth.png)",
        "",
        "## 4. Does optimisation beat 1/N?",
        "",
        "Sharpe ratio difference vs 1/N, circular block bootstrap (21-day blocks, "
        f"{ctx['n_boot']} resamples), two-sided p-value.",
        "",
        _md(ctx["tests"], ".3f"),
        "",
        "![Sharpe test](figures/sharpe_vs_1n.png)",
        "",
        "## 5. Stress periods (cumulative return %)",
        "",
        _md(ctx["periods"]),
        "",
        "## 6. Transaction costs (Sharpe ratio by cost level, bp)",
        "",
        _md(ctx["costs"].T.rename_axis("strategy")),
        "",
        "![Costs](figures/costs.png)",
        "",
        "## 7. Allocations over time",
        "",
        "![Weights](figures/weights.png)",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines))
    return path
